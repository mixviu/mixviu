#[cfg(test)]
mod tests {
    use super::*;
    use crate::drive::contract_tests::spec_list;
    #[test]
    fn key_names_match_spec_and_previous_parser() {
        let names = spec_list("<!-- key-names -->");
        assert_eq!(names.len(), KEY_NAMES.len());
        for (name, key) in KEY_NAMES {
            assert!(names.iter().any(|n| n == name), "{name:?}");
            assert_eq!(key_name(name), Some(*key));
            assert_eq!(Key::from_name(name), Some(*key));
        }
        for name in names {
            assert!(key_name(&name).is_some(), "{name:?}");
        }
        // Reverse coverage for every spelling egui can enumerate. Aliases that
        // exist only in from_name match arms cannot be enumerated by this API.
        // The 268-entry table was derived from every string literal in the
        // egui 0.37.0 Key::from_name match arms, including those aliases.
        for &key in Key::ALL {
            for name in [key.name(), key.symbol_or_name()] {
                assert_eq!(key_name(name), Some(key), "{name:?}");
            }
        }
        assert!(key_name("NoSuchKey").is_none());
    }
    #[test]
    fn role_names_match_spec() {
        let names = spec_list("<!-- role-names -->");
        assert_eq!(names, ROLES.iter().copied().map(role_name).collect::<Vec<_>>());
        for &role in ROLES {
            assert_eq!(role_name(role), format!("{role:?}"));
        }
    }
}
